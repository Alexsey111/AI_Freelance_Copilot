def catalog(query: str | None = None) -> list[dict]:
    """Справочник навыков, при необходимости отфильтрованный по подстроке."""
    needle = (query or "").strip().lower()
    result: list[dict] = []
    for profession in PROFESSIONS:
        skills = (
            [s for s in profession.skills if needle in s.lower()]
            if needle
            else list(profession.skills)
        )
        if not skills and needle:
            continue
        result.append({"key": profession.key, "title": profession.title, "skills": skills})
    return result


def all_skills() -> list[str]:
    seen: list[str] = []
    for profession in PROFESSIONS:
        for skill in profession.skills:
            if skill not in seen:
                seen.append(skill)
    return seen
