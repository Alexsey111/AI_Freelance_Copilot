-- 0005: оценка трудозатрат и ставка за час.
--
-- Порог «от 50 000 ₽» отсекает не плохие заказы, а мелкие: четыре заказа по 15 000 ₽ —
-- это 60 000 ₽ и, возможно, отличная неделя, а фильтр их не пропустит. Сравнивать надо
-- не бюджет, а ставку: бюджет / часы работы. 15 000 ₽ за 8 часов — 1 875 ₽/ч, это лучше,
-- чем 50 000 ₽ за 60 часов (833 ₽/ч).
--
-- Часы — наша оценка (`estimated_hours`), а не факт: она ставится при разборе заказа.
-- NULL означает «не оценено», и тогда вердикт по ставке не выносится: подставлять
-- средние 8 минут из замера нельзя, это разное время.

ALTER TABLE orders ADD COLUMN estimated_hours REAL;
