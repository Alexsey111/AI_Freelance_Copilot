-- 0003: восстановление момента постановки в очередь для уже висящих решений.
--
-- 0002 добавила queued_at, но у заказов, которые уже лежат в проверке, поле пустое —
-- и «сколько висит» для них не считается. Начало очереди восстанавливаем по времени
-- последнего анализа: именно он отправил заказ человеку. Это оценка снизу (заказ мог
-- попасть в проверку раньше, при создании), но она честнее пустого поля.
-- Затрагиваются только заказы, которые ждут решения прямо сейчас.

UPDATE orders
SET queued_at = (
    SELECT MAX(a.created_at)
    FROM analyses a
    WHERE a.order_id = orders.id
)
WHERE needs_review = 1
  AND queued_at IS NULL
  AND EXISTS (SELECT 1 FROM analyses a WHERE a.order_id = orders.id);
