-- 0004: конкуренция по карточке заказа — просмотры и ответы.
--
-- На карточке FL.ru, кроме времени публикации, видно «больше 300 просмотров» и «9 ответов».
-- Возраст сам по себе — плохой индикатор: заказ может быть свежим, но уже с 40 откликами.
-- Конкуренция считается по ответам: 9 ответов за 4 часа и 123 за сутки — разные вселенные,
-- при одинаковом возрасте разница в 13 раз.
--
-- Оба поля nullable: старые заказы их не имеют, и пустое поле честнее нуля
-- (ноль ответов и «данных нет» — это не одно и то же).

ALTER TABLE orders ADD COLUMN views INTEGER;
ALTER TABLE orders ADD COLUMN responses INTEGER;
