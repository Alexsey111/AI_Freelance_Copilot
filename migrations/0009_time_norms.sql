-- 0009: сколько времени уходит на какую задачу.
--
-- Оценка часов в заказе не должна каждый раз вводиться руками: у человека есть
-- представление «бот — это восемь часов, парсер — шесть, интеграция — десять».
-- Эти цифры живут здесь, правятся в окне программы, и из них собирается окно
-- распределения времени: сколько часов уйдёт на типы задач и сколько останется.
--
-- keywords — JSON-массив слов, по которым заказ относится к типу. Никакой модели:
-- сопоставление детерминированное и объяснимое («часы взяты из нормы "бот": в тексте
-- встретилось "telegram-бот"»), что для диплома важнее умности.

CREATE TABLE IF NOT EXISTS time_norms (
    task_kind TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    hours REAL NOT NULL,
    keywords TEXT NOT NULL DEFAULT '[]',
    note TEXT,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
